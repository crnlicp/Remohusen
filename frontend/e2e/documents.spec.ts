async function isolate(context: BrowserContext, remote: string[]) {
  const transport = await request.newContext();
  context.on("close", () => { void transport.dispose(); });
  await context.route("**/*", async (route) => {
    const url = new URL(route.request().url());
    if (url.protocol === "data:" || url.protocol === "blob:") return route.continue();
    if (!(url.hostname === "localhost" || url.hostname.endsWith(".localhost")) || url.port !== "8010") {
      remote.push(url.origin); return route.abort();
    }
    const response = await transport.fetch(`http://127.0.0.1:8010${url.pathname}${url.search}`, {
      method: route.request().method(), data: route.request().postDataBuffer() ?? undefined,
      headers: { ...route.request().headers(), host: url.host },
    });
    await route.fulfill({ response, headers: { ...response.headers(), "set-cookie": `ic_env=${cookie}; Path=/; SameSite=Lax` } });
  });
}
